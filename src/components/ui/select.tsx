import * as React from 'react'
import { Select as SelectPrimitive } from '@base-ui/react/select'

import { cn } from '../../lib/utils'

/**
 * Drawn in place rather than imported from `./icons`. This module is reachable
 * from the entry chunk (the theme control and the shell both pull it in), and
 * the entry chunk is held to a gzip budget plus a purity grep over its source
 * text — so the three glyphs a select needs live here as path data. Geometry
 * matches the shared icon set: 24 viewBox, round caps, and the size-compensated
 * 1.75 stroke `icons.tsx` uses at 16px — not the 1.5 it draws on the 24 grid.
 */
function Glyph({ d, className }: { readonly d: string; readonly className?: string }) {
  return (
    <svg
      aria-hidden="true"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
    >
      <path d={d} />
    </svg>
  )
}

const CHEVRON_DOWN = 'm19.5 8.25-7.5 7.5-7.5-7.5'
const CHEVRON_UP = 'm4.5 15.75 7.5-7.5 7.5 7.5'
const CHECK = 'm4.5 12.75 6 6 9-13.5'

